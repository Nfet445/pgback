window.t = function(key) {
  const lang = window.currentLanguage || 'en';
  return (window.translations[lang] && window.translations[lang][key]) || key;
};

window.setLanguage = function(lang) {
  window.currentLanguage = lang;
  localStorage.setItem('language', lang);
  document.documentElement.lang = lang;
  
  fetch('/api/language/' + lang, { method: 'POST' })
    .then(() => window.applyTranslations && window.applyTranslations());
};

window.getLanguage = function() {
  return localStorage.getItem('language') || 'en';
};

window.currentLanguage = window.getLanguage();
document.documentElement.lang = window.currentLanguage;
